-- =====================================================================
--  Sistema de Préstamos de Computadoras (IEN) — esquema para Supabase
--  PostgreSQL. Pegar completo en: Supabase > SQL Editor > New query > Run.
--  Ejecutar UNA sola vez sobre un proyecto vacío (no es re-ejecutable).
--
--  Equivalencias con el modelo local (Room/SQLite):
--    ADMINISTRADOR  -> perfil  (+ auth_user_id: vínculo con Supabase Auth;
--                               ya no existe contrasena_hash, la clave
--                               la guarda Supabase Auth)
--    id_usuario_prestamo / id_usuario_devolucion -> quién entregó / quién
--                               recibió la computadora (FK a perfil)
--    Fechas: antes epoch en milisegundos (Long), ahora timestamptz.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. TABLAS
-- ---------------------------------------------------------------------

create table public.rol (
  id_rol      bigint generated by default as identity primary key,
  nombre      text    not null unique,
  es_sistema  boolean not null default false
);

create table public.rol_permiso (
  id_rol   bigint not null references public.rol (id_rol) on delete cascade,
  permiso  text   not null,
  primary key (id_rol, permiso)
);

create table public.perfil (
  id_perfil       bigint generated by default as identity primary key,
  auth_user_id    uuid   not null unique references auth.users (id) on delete cascade,
  nombre          text   not null,
  apellido        text   not null,
  nombre_usuario  text   not null unique,
  dni             text   not null,
  email           text   not null unique,
  id_rol          bigint not null references public.rol (id_rol) on delete restrict
);

create table public.alumno (
  id_alumno  bigint generated by default as identity primary key,
  nombre     text not null,
  apellido   text not null,
  dni        text not null
);

create table public.computadora (
  id_computadora  bigint generated by default as identity primary key,
  codigo          text not null unique,   -- el que lleva el QR (PC-01, PC-02, ...)
  modelo          text
);

create table public.prestamo (
  id_prestamo              bigint generated by default as identity primary key,
  id_alumno                bigint not null references public.alumno (id_alumno)           on delete restrict,
  id_computadora           bigint not null references public.computadora (id_computadora) on delete restrict,
  id_usuario_prestamo      bigint not null references public.perfil (id_perfil)           on delete restrict,
  id_usuario_devolucion    bigint          references public.perfil (id_perfil)           on delete restrict,
  fecha_prestamo           timestamptz not null default now(),
  fecha_devolucion         timestamptz,
  estado                   text not null default 'ACTIVO'
                             check (estado in ('ACTIVO', 'DEVUELTO')),
  observaciones_iniciales  text,

  -- Un préstamo activo no tiene devolución; uno devuelto SIEMPRE tiene fecha
  -- y la persona que lo recibió (evita registros DEVUELTO con quién = NULL).
  constraint prestamo_estado_coherente check (
    (estado = 'ACTIVO'
       and fecha_devolucion is null
       and id_usuario_devolucion is null)
    or
    (estado = 'DEVUELTO'
       and fecha_devolucion is not null
       and id_usuario_devolucion is not null)
  )
);

create table public.estado_computadora (
  id_estado       bigint generated by default as identity primary key,
  id_prestamo     bigint not null unique                     -- 1 a 1 con prestamo
                    references public.prestamo (id_prestamo) on delete cascade,
  enciende        boolean not null,
  pantalla_ok     boolean not null,
  cargador        boolean not null,
  observaciones   text,
  fecha_revision  timestamptz not null default now()
);


-- ---------------------------------------------------------------------
-- 2. ÍNDICES Y REGLAS DE UNICIDAD
-- ---------------------------------------------------------------------

-- Un solo Admin en todo el sistema (id_rol = 1). Reemplaza a los triggers
-- un_solo_admin_insert / un_solo_admin_update de SQLite: el índice parcial
-- logra lo mismo y además es seguro ante inserciones simultáneas.
create unique index un_solo_admin on public.perfil (id_rol) where id_rol = 1;

-- Una computadora no puede tener dos préstamos ACTIVOS a la vez.
-- (En la base local esto lo garantizaba solo la app.)
create unique index prestamo_un_activo_por_computadora
  on public.prestamo (id_computadora) where estado = 'ACTIVO';

-- Índices sobre claves foráneas y columnas usadas en Home / Historial
create index perfil_id_rol_idx                on public.perfil   (id_rol);
create index prestamo_id_alumno_idx           on public.prestamo (id_alumno);
create index prestamo_id_usuario_prestamo_idx on public.prestamo (id_usuario_prestamo);
create index prestamo_id_usuario_devol_idx    on public.prestamo (id_usuario_devolucion);
create index prestamo_fecha_prestamo_idx      on public.prestamo (fecha_prestamo desc);
create index prestamo_fecha_devolucion_idx    on public.prestamo (fecha_devolucion desc);


