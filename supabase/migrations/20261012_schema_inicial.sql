-- ---------------------------------------------------------------------
-- 4. FUNCIONES AUXILIARES
-- ---------------------------------------------------------------------

-- ¿El usuario logueado es Admin?
create or replace function public.es_admin()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.perfil
    where auth_user_id = (select auth.uid()) and id_rol = 1
  );
$$;

-- id_perfil del usuario logueado (para el "gestionado por")
create or replace function public.mi_perfil_id()
returns bigint
language sql stable security definer set search_path = ''
as $$
  select id_perfil from public.perfil
  where auth_user_id = (select auth.uid());
$$;

-- Tarjetas del Home: préstamos activos ahora + devoluciones de HOY
-- (el "hoy" se calcula en hora de Argentina, no en UTC)
create or replace function public.resumen_hoy()
returns table (prestados bigint, devueltos_hoy bigint)
language sql stable security invoker set search_path = ''
as $$
  select
    (select count(*) from public.prestamo where estado = 'ACTIVO'),
    (select count(*) from public.prestamo
      where estado = 'DEVUELTO'
        and (fecha_devolucion at time zone 'America/Argentina/Buenos_Aires')::date
          = (now()           at time zone 'America/Argentina/Buenos_Aires')::date);
$$;


-- ---------------------------------------------------------------------
-- 5. ALTA AUTOMÁTICA DE PERFIL AL REGISTRARSE
--    Cada vez que Supabase Auth crea un usuario, se crea su perfil:
--    el PRIMERO queda como Admin (rol 1); todos los siguientes, como
--    Personal Administrativo (rol 2).
--    Datos que la app debe mandar al registrar (signUp > data):
--      nombre, apellido, nombre_usuario, dni
-- ---------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
declare
  v_rol bigint;
begin
  -- evita que dos primeros registros simultáneos se pisen
  perform pg_advisory_xact_lock(hashtext('perfil_primer_admin'));

  if exists (select 1 from public.perfil where id_rol = 1) then
    v_rol := 2;
  else
    v_rol := 1;
  end if;

  insert into public.perfil (auth_user_id, nombre, apellido, nombre_usuario, dni, email, id_rol)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'nombre', ''),
    coalesce(new.raw_user_meta_data ->> 'apellido', ''),
    coalesce(new.raw_user_meta_data ->> 'nombre_usuario', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'dni', ''),
    new.email,
    v_rol
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();


-- ---------------------------------------------------------------------
-- 6. VISTA PARA HISTORIAL Y "ACTIVIDAD RECIENTE"
--    Una fila por préstamo, con los nombres ya resueltos:
--      Prestado por: prestado_por · Devuelto por: devuelto_por
--    Home (actividad reciente): order by ultima_actividad desc limit 5
-- ---------------------------------------------------------------------

create or replace view public.historial_prestamos
with (security_invoker = true) as
select
  p.id_prestamo,
  p.estado,
  p.fecha_prestamo,
  p.fecha_devolucion,
  coalesce(p.fecha_devolucion, p.fecha_prestamo) as ultima_actividad,
  p.observaciones_iniciales,
  p.id_alumno,
  a.nombre   as alumno_nombre,
  a.apellido as alumno_apellido,
  a.dni      as alumno_dni,
  p.id_computadora,
  c.codigo   as computadora_codigo,
  c.modelo   as computadora_modelo,
  p.id_usuario_prestamo,
  up.nombre || ' ' || up.apellido as prestado_por,
  p.id_usuario_devolucion,
  ud.nombre || ' ' || ud.apellido as devuelto_por,
  e.enciende,
  e.pantalla_ok,
  e.cargador,
  e.observaciones as observaciones_devolucion
from public.prestamo p
join public.alumno      a  on a.id_alumno      = p.id_alumno
join public.computadora c  on c.id_computadora = p.id_computadora
join public.perfil      up on up.id_perfil     = p.id_usuario_prestamo
left join public.perfil ud on ud.id_perfil     = p.id_usuario_devolucion
left join public.estado_computadora e on e.id_prestamo = p.id_prestamo;


-- ---------------------------------------------------------------------
-- 7. SEGURIDAD (Row Level Security)
--    Sin esto, cualquiera con la clave pública de la app podría leer y
--    modificar todo. Reglas:
--      - Todos los usuarios logueados LEEN todo.
--      - Solo el Admin crea/edita alumnos, computadoras, roles y perfiles.
--      - Cualquier usuario logueado registra préstamos y devoluciones,
--        pero el "prestado por" debe ser él mismo (no se puede falsear).
--      - Sin sesión (anon): no ve ni modifica nada.
-- ---------------------------------------------------------------------

alter table public.rol                enable row level security;
alter table public.rol_permiso        enable row level security;
alter table public.perfil             enable row level security;
alter table public.alumno             enable row level security;
alter table public.computadora        enable row level security;
alter table public.prestamo           enable row level security;
alter table public.estado_computadora enable row level security;

-- Lectura para cualquier usuario logueado
create policy rol_leer                on public.rol                for select to authenticated using (true);
create policy rol_permiso_leer        on public.rol_permiso        for select to authenticated using (true);
create policy perfil_leer             on public.perfil             for select to authenticated using (true);
create policy alumno_leer             on public.alumno             for select to authenticated using (true);
create policy computadora_leer        on public.computadora        for select to authenticated using (true);
create policy prestamo_leer           on public.prestamo           for select to authenticated using (true);
create policy estado_computadora_leer on public.estado_computadora for select to authenticated using (true);

-- Escritura solo Admin
create policy rol_admin_escribe         on public.rol         for all to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy rol_permiso_admin_escribe on public.rol_permiso for all to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy perfil_admin_escribe      on public.perfil      for all to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy alumno_admin_escribe      on public.alumno      for all to authenticated
  using (public.es_admin()) with check (public.es_admin());
create policy computadora_admin_escribe on public.computadora for all to authenticated
  using (public.es_admin()) with check (public.es_admin());

-- Préstamos: cualquier usuario logueado, pero "prestado por" = él mismo
create policy prestamo_crear on public.prestamo for insert to authenticated
  with check (id_usuario_prestamo = public.mi_perfil_id());
create policy prestamo_actualizar on public.prestamo for update to authenticated
  using (true) with check (true);
create policy prestamo_admin_borra on public.prestamo for delete to authenticated
  using (public.es_admin());

-- Revisión del equipo: cualquier usuario logueado crea/edita; Admin borra
create policy estado_computadora_crear on public.estado_computadora for insert to authenticated
  with check (true);
create policy estado_computadora_actualizar on public.estado_computadora for update to authenticated
  using (true) with check (true);
create policy estado_computadora_admin_borra on public.estado_computadora for delete to authenticated
  using (public.es_admin());


-- ---------------------------------------------------------------------
-- 8. PERMISOS DE ACCESO (API)
-- ---------------------------------------------------------------------

revoke all on all tables    in schema public from anon;
revoke all on all functions in schema public from anon;

grant select, insert, update, delete on all tables in schema public to authenticated;

revoke execute on function public.es_admin()     from public, anon;
revoke execute on function public.mi_perfil_id() from public, anon;
revoke execute on function public.resumen_hoy()  from public, anon;

grant execute on function public.es_admin()     to authenticated;
grant execute on function public.mi_perfil_id() to authenticated;
grant execute on function public.resumen_hoy()  to authenticated;


