--  Aulas — Sistema de Préstamos de Computadoras (IEN)
--  Pegar completo en: Supabase > SQL Editor > New query > Run.
--  Ejecutar UNA sola vez, DESPUÉS de las migraciones anteriores.
--
--  - Tabla aula (id_aula, nombre) con nombre único sin distinguir mayúsculas.
--  - prestamo.id_aula: a qué aula se llevó el equipo. Admite NULL porque los
--    préstamos viejos no tienen aula.
--  - La vista historial_prestamos suma id_aula y aula_nombre AL FINAL (el resto
--    de las columnas y su orden quedan igual).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. TABLA
-- ---------------------------------------------------------------------

create table public.aula (
  id_aula  bigint generated by default as identity primary key,
  nombre   text   not null
);

-- No puede haber dos aulas con el mismo nombre, sin importar mayúsculas
-- ("Aula 1" y "aula 1" chocan). Error 23505 con este nombre de índice.
create unique index aula_nombre_unico on public.aula (lower(nombre));


-- ---------------------------------------------------------------------
-- 2. PRESTAMO -> AULA
--    ON DELETE RESTRICT: no se puede borrar un aula que ya tuvo préstamos
--    (error 23503 de clave foránea).
-- ---------------------------------------------------------------------

alter table public.prestamo
  add column id_aula bigint references public.aula (id_aula) on delete restrict;

create index prestamo_id_aula_idx on public.prestamo (id_aula);


-- ---------------------------------------------------------------------
-- 3. VISTA historial_prestamos
--    Mismas columnas y mismo orden que antes + id_aula y aula_nombre al final
--    (create or replace view solo permite sumar columnas al final).
-- ---------------------------------------------------------------------

create or replace view public.historial_prestamos
with (security_invoker = true) as
select
  p.id_prestamo,
  p.estado,
  p.fecha_prestamo,
  p.fecha_devolucion,
  coalesce(p.fecha_devolucion, p.fecha_prestamo) as ultima_actividad,
  p.observaciones_iniciales,
  p.id_alumno,
  a.nombre   as alumno_nombre,
  a.apellido as alumno_apellido,
  a.dni      as alumno_dni,
  p.id_computadora,
  c.codigo   as computadora_codigo,
  c.modelo   as computadora_modelo,
  p.id_usuario_prestamo,
  up.nombre || ' ' || up.apellido as prestado_por,
  p.id_usuario_devolucion,
  ud.nombre || ' ' || ud.apellido as devuelto_por,
  e.enciende,
  e.pantalla_ok,
  e.cargador,
  e.observaciones as observaciones_devolucion,
  p.id_aula,
  au.nombre  as aula_nombre
from public.prestamo p
join public.alumno      a  on a.id_alumno      = p.id_alumno
join public.computadora c  on c.id_computadora = p.id_computadora
join public.perfil      up on up.id_perfil     = p.id_usuario_prestamo
left join public.perfil ud on ud.id_perfil     = p.id_usuario_devolucion
left join public.estado_computadora e on e.id_prestamo = p.id_prestamo
left join public.aula   au on au.id_aula       = p.id_aula;


-- ---------------------------------------------------------------------
-- 4. SEGURIDAD (RLS): leer cualquier usuario logueado, escribir solo el Admin
-- ---------------------------------------------------------------------

alter table public.aula enable row level security;

create policy aula_leer on public.aula for select to authenticated using (true);

create policy aula_admin_escribe on public.aula for all to authenticated
  using (public.es_admin()) with check (public.es_admin());


-- ---------------------------------------------------------------------
-- 5. PERMISOS DE ACCESO (API)
--    La tabla es nueva: no hereda los grants del esquema inicial.
-- ---------------------------------------------------------------------

revoke all on public.aula from anon;
grant select, insert, update, delete on public.aula to authenticated;
